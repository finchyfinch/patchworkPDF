MAPS = {"es": ES, "fr": FR, "de": DE, "it": IT}


def build(lang: str, en: dict) -> dict:
    """Complete locale = English base overlaid with the language's translations."""
    out = dict(en)
    out.update({k: v for k, v in MAPS[lang].items() if k in en})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lang", choices=list(MAPS), help="build just one language")
    ap.add_argument("--check", action="store_true",
                    help="report coverage only; write nothing")
    args = ap.parse_args()

    with open(os.path.join(LOCALES, "en.json"), "r", encoding="utf-8") as f:
        en = json.load(f)

    langs = [args.lang] if args.lang else [l for l in MAPS if MAPS[l]]
    for lang in langs:
        m = MAPS[lang]
        translated = sum(1 for k in m if k in en)
        unknown = [k for k in m if k not in en]      # keys that no longer exist
        pct = round(100 * translated / len(en)) if en else 0
        print(f"{lang}: {translated}/{len(en)} keys translated ({pct}%), "
              f"{len(unknown)} stale.")
        for k in unknown:
            print(f"    ! stale key not in en.json: {k}")
        if not args.check:
            data = build(lang, en)
            with open(os.path.join(LOCALES, f"{lang}.json"), "w",
                      encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
                f.write("\n")


if __name__ == "__main__":
    main()
